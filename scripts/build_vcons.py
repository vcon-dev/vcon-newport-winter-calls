#!/usr/bin/env python3
"""Build vcons/*.vcon.json from build/specs.jsonl + transcripts (docs/pipeline.md).

Usage: build_vcons.py [--clean]
  --clean   delete vcon files that this run does not (re)write
"""
import json
import sys
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEPT_NAMES = {
    "public-works": "Public Works", "utilities": "Utilities", "finance": "Finance",
    "city-clerk": "City Clerk", "zoning-and-inspections": "Zoning and Inspections",
    "recreation": "Recreation", "canvassing": "Canvassing",
}
SPEAKER_IDX = {"caller": 0, "clerk": 1}


def allocate(words, total):
    """Integer seconds per turn, proportional to word count, min 1 each, sum exactly total."""
    n = len(words)
    if total < n:
        raise ValueError(f"{n} turns cannot fit in {total} s")
    extra = total - n
    wsum = sum(max(w, 1) for w in words)
    raw = [extra * max(w, 1) / wsum for w in words]
    base = [int(r) for r in raw]
    rem = extra - sum(base)
    order = sorted(range(n), key=lambda i: (-(raw[i] - base[i]), i))
    for i in order[:rem]:
        base[i] += 1
    return [1 + b for b in base]


def find_transcript(spec):
    """Return (path, warning) or (None, None)."""
    uid = spec["uuid"]
    fallback = ROOT / "build" / "transcripts" / f"{uid}.json"
    if spec.get("fixed_transcript"):
        p = ROOT / spec["fixed_transcript"]
        if p.exists():
            return p, None
        if fallback.exists():
            return fallback, f"fixed transcript {spec['fixed_transcript']} missing, using {fallback.relative_to(ROOT)}"
        return None, None
    return (fallback, None) if fallback.exists() else (None, None)


def build(spec, tr):
    turns = tr["turns"]
    if not turns:
        raise ValueError("no turns")
    for t in turns:
        if t.get("speaker") not in SPEAKER_IDX or not isinstance(t.get("text"), str) or not t["text"].strip():
            raise ValueError(f"bad turn {t!r}")
    start = datetime.fromisoformat(spec["start"])
    dur = spec["duration_s"]
    end = start + timedelta(seconds=dur)
    durs = allocate([len(t["text"].split()) for t in turns], dur)
    assert sum(durs) == dur
    dialog = []
    off = 0
    for t, d in zip(turns, durs):
        idx = SPEAKER_IDX[t["speaker"]]
        dialog.append({
            "type": "text", "start": (start + timedelta(seconds=off)).isoformat(), "duration": d,
            "parties": [idx], "originator": idx, "mediatype": "text/plain", "encoding": "none", "body": t["text"],
        })
        off += d
    s_iso = start.isoformat()

    def att(purpose, body):
        return {"purpose": purpose, "party": 0, "dialog": 0, "start": s_iso,
                "mediatype": "application/json", "encoding": "json", "body": body}

    grants = [{"purpose": p, "granted": True, "granted_at": s_iso}
              for p in ("recording", "transcription", "analysis", "redistribution")]
    vcon = {
        "vcon": "0.4.0",
        "uuid": spec["uuid"],
        "created_at": end.isoformat(),
        "subject": f"Inbound call, {DEPT_NAMES[spec['department']]}",
        "parties": [
            {"name": spec["caller"]["name"], "role": "resident", "validation": "synthetic"},
            {"name": spec["clerk"]["name"], "role": "clerk", "validation": "synthetic"},
        ],
        "dialog": dialog,
        "attachments": [
            att("tags", {"department": spec["department"]}),
            att("call_detail", {"direction": "inbound", "start": s_iso, "end": end.isoformat(),
                                "duration_seconds": dur, "channel": spec["channel"]}),
            att("lawful_basis", {
                "lawful_basis": "legitimate_interests", "expiration": None, "purpose_grants": grants,
                "proof_mechanisms": [{"mechanism_type": "external_system",
                                      "description": "Synthetic corpus generated by vcon-dev/vcon-newport-winter-calls; no real data subject"}],
            }),
        ],
        "extensions": ["lawful_basis"],
    }
    return vcon


def filename(spec):
    s = datetime.fromisoformat(spec["start"])
    return f"{s:%Y-%m-%d}-{s:%H%M}-{spec['department']}-{spec['uuid'][:8]}.vcon.json"


def main():
    clean = "--clean" in sys.argv
    out_dir = ROOT / "vcons"
    out_dir.mkdir(exist_ok=True)
    specs = [json.loads(l) for l in (ROOT / "build" / "specs.jsonl").read_text().splitlines() if l.strip()]
    written, missing, warns, errors = set(), [], [], []
    for sp in specs:
        p, w = find_transcript(sp)
        if p is None:
            missing.append(sp["uuid"])
            continue
        if w:
            warns.append(f"{sp['uuid']}: {w}")
        try:
            tr = json.loads(p.read_text())
            if tr.get("uuid") not in (sp["uuid"], "PLANNED_BY_plan_corpus"):
                warns.append(f"{sp['uuid']}: transcript uuid {tr.get('uuid')!r} differs; using spec uuid")
            v = build(sp, tr)
        except Exception as e:  # report and continue
            errors.append(f"{sp['uuid']}: {e}")
            continue
        name = filename(sp)
        (out_dir / name).write_text(json.dumps(v, indent=2, ensure_ascii=False) + "\n")
        written.add(name)
    removed = 0
    if clean:
        for f in out_dir.glob("*.vcon.json"):
            if f.name not in written:
                f.unlink()
                removed += 1
    for w in warns:
        print("WARNING", w)
    for e in errors:
        print("ERROR", e)
    print(f"specs {len(specs)}, built {len(written)}, no transcript yet {len(missing)}, errors {len(errors)}, removed stale {removed}")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
